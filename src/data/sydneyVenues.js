export function curatedVenuesForDate(date) {
  const month = Number(date.slice(5, 7)) - 1;
  return sydneyVenues.map((v) =>
    v.seasonalClose
      ? { ...v, weeklyHours: daily(420, v.seasonalClose[month]) }
      : v,
  );
}
