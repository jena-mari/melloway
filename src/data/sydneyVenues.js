const checkedAt = "2026-10-11";
const window = (open, close) => ({ open, close });
const daily = (open, close) =>
  Array.from({ length: 7 }, () => [window(open, close)]);
const weekly = (pairs) =>
  pairs.map((day) => day.map(([open, close]) => window(open, close)));
function place(
  id,
  name,
  address,
  lat,
  lng,
  category,
  tags,
  roles,
  atmosphere,
  cost,
  mins,
  weeklyHours,
  website,
  description,
  extra = {},
) {
  return {
    id: `sydney-${id}`,
    name,
    address,
    lat,
    lng,
    area: address.includes("Newtown")
      ? "Newtown"
      : address.includes("Darlinghurst")
        ? "Surry Hills"
        : "Sydney CBD",
    category,
    tags,
    roles,
    atmosphere,
    cost,
    mins,
    weeklyHours,
    source: "curated",
    website,
    sources: [
      {
        url: website,
        checkedAt,
        fields: ["name", "address", "published hours"],
      },
    ],
    hoursStatus: weeklyHours ? "published" : "unconfirmed",
    checkedAt,
    coordinatesStatus: "approximate",
    priceStatus: "estimate",
    description,
    note: "Published hours checked 11 Oct 2026; confirm changes and bookings. Spend and visit length are allowances; map position is approximate.",
    ...extra,
  };
}

